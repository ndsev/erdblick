import {load} from "js-yaml";
import {
    beforeAll,
    describe,
    expect,
    it
} from "vitest";

import {coreLib, initializeLibrary, uint8ArrayToWasm} from "../../../app/integrations/wasm.adapter";
import type {FeatureSearchStyleRule} from "../../../app/search/search-definition.model";
import {
    canonicalLayerAffinityExpression,
    canonicalSearchStyleFilename,
    convertSearchStyleRulesToYaml as exportSearchStyle,
    featureSearchRulesToStyleRules,
    decodeCanonicalLayerAffinity,
    projectStyleSourceForSearch,
    updateStyleSourceMetadata
} from "../../../app/search/search-style-sheet.converter";

/** Supplies the explicit unfiltered feature membership used by the codec fixtures. */
function convertSearchStyleRulesToYaml(
    options: Parameters<typeof exportSearchStyle>[0],
    rules: Parameters<typeof exportSearchStyle>[1],
    context: Parameters<typeof exportSearchStyle>[2] = {
        concreteScope: "feature", backendQuery: "", selectedFeatureTypes: []
    }
) {
    return exportSearchStyle(options, rules, context);
}

describe("search style sheet codec", () => {
    beforeAll(async () => {
        await initializeLibrary();
    });

    const rules: FeatureSearchStyleRule[] = [
        {
            name: "UI-only name",
            autoGenerated: true,
            geometry: ["line"],
            filter: [{field: "speed", op: ">=", value: 80}],
            color: {mode: "solid", color: "#ff0000"},
            width: 7,
            opacity: 0.8
        },
        {
            geometry: ["point"],
            filter: [],
            color: {mode: "solid", color: "#00ff00"},
            pointRadius: 8
        },
        {
            geometry: ["label"],
            filter: [],
            color: {mode: "solid", color: "#ffffff"},
            opacity: 0.5,
            width: 22,
            labelExpression: "typeId",
            labelBackgroundColor: "#000000"
        }
    ];

    const saveOptions = (
        name: string,
        defaultEnabled = false,
        layerIds: readonly string[] = []
    ) => ({name, defaultEnabled, layerIds});

    it.each(["gradient", "categories"] as const)("preserves an omitted %s fallback through YAML", mode => {
        const rule: FeatureSearchStyleRule = {geometry: ["line"], filter: [], width: 2,
            color: {mode, field: "speed", stops: [{value: 10, color: "#123456"}]}};
        const saved = convertSearchStyleRulesToYaml(saveOptions("No fallback"), [rule]);
        expect((load(saved.source) as any).rules[0]["color-scale"]).not.toHaveProperty("fallback");
        const loaded = projectStyleSourceForSearch(saved.source, "feature");
        expect(loaded.rules[0].color).not.toHaveProperty("fallbackColor");
    });

    it("emits deterministic exact-name category-search YAML with flat rules", () => {
        const first = convertSearchStyleRulesToYaml(saveOptions("Team/Road emphasis"), rules);
        const second = convertSearchStyleRulesToYaml(saveOptions("Team/Road emphasis"), rules);
        const parsed = load(first.source) as any;

        expect(first).toEqual(second);
        expect(parsed.name).toBe("Team/Road emphasis");
        expect(parsed.category).toBe("search");
        expect(parsed.default).toBe(false);
        expect(parsed.version).toBe(2);
        expect(parsed.options).toEqual([{
            label: "Show Team/Road emphasis",
            id: "showSearchStyle",
            type: "bool",
            default: true
        }]);
        expect(parsed.rules).toHaveLength(3);
        expect(parsed.rules[0]).not.toHaveProperty("all-of");
        expect(parsed.rules[0].scope).toBe("feature");
        expect(parsed.rules[0].geometry).toEqual(["line"]);
        expect(parsed.rules[0]["z-index"]).toBe(Number.MAX_SAFE_INTEGER);
        expect(parsed.rules[0].filter).toBe("showSearchStyle == true and (any(speed >= 80))");
        expect(parsed.rules[1].filter).toBe("showSearchStyle == true");
        expect(parsed.rules[1].width).toBe(8);
        expect(parsed.rules[2]["label-background"]).toBe(true);
        expect(parsed.rules[2]["label-background-color"]).toBe("#000000");
        expect(parsed.rules[2]["label-size"]).toBeCloseTo(24 * 22 / 14);
        expect(first.source).not.toContain("UI-only name");
        expect(first.source).not.toContain("autoGenerated");
        expect(first.filename).toBe("Team-Road-emphasis.yaml");
    });

    it("produces a category-search sheet accepted by the native parser", () => {
        const generated = convertSearchStyleRulesToYaml(saveOptions("Team/Road emphasis"), rules);
        const style = uint8ArrayToWasm(
            wasmBuffer => new coreLib.FeatureLayerStyle(wasmBuffer),
            new TextEncoder().encode(generated.source)
        );

        expect(style.isValid(), JSON.stringify(style.validationReport())).toBe(true);
        expect(style.defaultEnabled()).toBe(false);
        expect(style.category()).toBe(coreLib.StyleCategory.Search);
        const options = style.options();
        expect(options.size()).toBe(1);
        expect(options.get(0)?.id).toBe("showSearchStyle");
        expect(options.get(0)?.defaultValue).toBe(true);
        options.delete();
        style.delete();
    });

    it.each(["feature", "attribute"] as const)("exports the live %s membership and native validity defaults", concreteScope => {
        const context = {concreteScope, backendQuery: "speedLimitKmh == 80",
            selectedFeatureTypes: ["Road", "Lane", "Road"]};
        const saved = convertSearchStyleRulesToYaml(saveOptions("Scoped"), rules, context);
        const parsed = load(saved.source) as any;
        const live = featureSearchRulesToStyleRules(rules, context);
        const key = concreteScope === "attribute" ? "attribute-filter" : "filter";
        const typeField = concreteScope === "attribute" ? "$feature.typeId" : "typeId";
        expect(parsed.rules[0].scope).toBe(concreteScope);
        expect(parsed.rules[0][key]).toBe(`showSearchStyle == true and (${live[0][key]})`);
        expect(parsed.rules[0][key]).toContain('any(speedLimitKmh == 80)');
        expect(parsed.rules[0][key]).toContain(`any(${typeField} == "Road" or ${typeField} == "Lane")`);
        expect(parsed.rules[0]).not.toHaveProperty("attribute-validity-geom");
        if (concreteScope === "attribute") expect(parsed.rules[0]).not.toHaveProperty("filter");
        const style = uint8ArrayToWasm(buffer => new coreLib.FeatureLayerStyle(buffer),
            new TextEncoder().encode(saved.source));
        try {
            expect(style.isValid(), JSON.stringify(style.validationReport())).toBe(true);
        } finally { style.delete(); }
    });

    it("retains captured predicates when reusing a saved style in another search", () => {
        const generated = convertSearchStyleRulesToYaml(saveOptions("Round trip"), rules);
        const projected = projectStyleSourceForSearch(generated.source, "feature");
        const regenerated = convertSearchStyleRulesToYaml(saveOptions("Round trip copy"), projected.rules);
        const first = load(generated.source) as any;
        const second = load(regenerated.source) as any;

        expect(projected.omissions).toEqual([]);
        expect(projected.rules[0].filter[0].field).toBe("any(speed >= 80)");
        expect(second.rules[0].filter).toContain("any(any(speed >= 80))");
        expect(second.rules.map((rule: any) => rule.color)).toEqual(first.rules.map((rule: any) => rule.color));
    });




    it("does not strip a visibility-like prefix that does not gate the complete filter", () => {
        const source = `
name: Custom gate
category: search
version: 2
options:
  - {label: Show Custom gate, id: showSearchStyle, type: bool, default: true}
rules:
  - geometry: line
    filter: 'showSearchStyle == true and (kind == "a") or (kind == "b")'
    color: '#ea4336'
`;
        const projection = projectStyleSourceForSearch(source, "feature");

        expect(projection.rules[0].filter[0].field)
            .toBe('showSearchStyle == true and (kind == "a") or (kind == "b")');
    });

    it("rejects empty rules and values conversion cannot preserve", () => {
        expect(() => convertSearchStyleRulesToYaml(saveOptions("Empty"), [])).toThrow(/at least one/i);
        expect(() => convertSearchStyleRulesToYaml(saveOptions("Broken"), [{
            geometry: ["line"],
            filter: [{field: "speed", op: "approximately", value: 80}],
            color: {
                mode: "categories",
                field: "kind",
                stops: [{value: {nested: true}, color: "#ffffff"}]
            }
        }])).toThrow(/unsupported operator.*non-scalar value/i);
    });

    it("emits the chosen default and exact deterministic layer affinity", () => {
        const generated = convertSearchStyleRulesToYaml(
            saveOptions("Scoped", true, ["roads.v2", "lane[0]", "roads.v2"]),
            rules);
        const parsed = load(generated.source) as any;
        const style = uint8ArrayToWasm(
            wasmBuffer => new coreLib.FeatureLayerStyle(wasmBuffer),
            new TextEncoder().encode(generated.source)
        );

        expect(parsed.default).toBe(true);
        expect(parsed.layer).toBe("^(lane\\[0\\]|roads\\.v2)$");
        expect(style.defaultEnabled()).toBe(true);
        expect(style.hasLayerAffinity("lane[0]")).toBe(true);
        expect(style.hasLayerAffinity("roads.v2")).toBe(true);
        expect(style.hasLayerAffinity("roadsXv2")).toBe(false);
        style.delete();
    });

    it("omits affinity for Any and preserves exact whitespace-bearing IDs", () => {
        const any = load(convertSearchStyleRulesToYaml(
            saveOptions("Any", false, []), rules).source) as any;
        const exact = convertSearchStyleRulesToYaml(
            saveOptions("Whitespace", false, [" roads "]), rules);
        const style = uint8ArrayToWasm(
            wasmBuffer => new coreLib.FeatureLayerStyle(wasmBuffer),
            new TextEncoder().encode(exact.source)
        );

        expect(any).not.toHaveProperty("layer");
        expect(style.hasLayerAffinity(" roads ")).toBe(true);
        expect(style.hasLayerAffinity("roads")).toBe(false);
        style.delete();
    });

    it("projects and losslessly updates Quick name and layer affinity metadata", () => {
        const exactIds = [" roads ", "lane[0]", "pipe|slash\\value"];
        const exactExpression = canonicalLayerAffinityExpression(exactIds);
        const source = `# retained root comment
name: Original
layer: ${JSON.stringify(exactExpression)}
custom-root: retained
rules:
  - geometry: [line] # retained rule comment
    color: "#ff0000"
`;
        expect(decodeCanonicalLayerAffinity(exactExpression)).toEqual([...exactIds].sort());
        expect(decodeCanonicalLayerAffinity("Road.*")).toBeUndefined();

        const renamed = updateStyleSourceMetadata(source, {name: "Renamed: Style"});
        const cleared = updateStyleSourceMetadata(renamed, {layerAffinity: {kind: "any"}});
        const parsed = load(cleared) as any;
        expect(cleared).toContain("# retained root comment");
        expect(cleared).toContain("# retained rule comment");
        expect(parsed.name).toBe("Renamed: Style");
        expect(parsed).not.toHaveProperty("layer");
        expect(parsed["custom-root"]).toBe("retained");


    });

    it("keeps the generated visibility label synchronized with a Quick rename", () => {
        const source = convertSearchStyleRulesToYaml(
            saveOptions("Original Search"),
            rules
        ).source;

        const renamed = updateStyleSourceMetadata(source, {name: "Renamed/Search"});
        const parsed = load(renamed) as any;

        expect(parsed.name).toBe("Renamed/Search");
        expect(parsed.options).toEqual([{
            label: "Show Renamed/Search",
            id: "showSearchStyle",
            type: "bool",
            default: true
        }]);
        expect(parsed.rules[0].filter).toBe("showSearchStyle == true and (any(speed >= 80))");
    });

    it("applies only effective compatible rules and reports every omission", () => {
        const source = `
name: Mixed/Search
category: search
version: 2
rules:
  - scope: feature
    geometry: line
    color: "#ff0000"
  - scope: attribute
    geometry: point
    color: "#00ff00"
  - geometry: line
    first-of:
      - color: "#0000ff"
`;
        const feature = projectStyleSourceForSearch(source, "feature");

        expect(feature.rules).toHaveLength(1);
        expect(feature.totalRuleCount).toBe(3);
        expect(feature.omissions.map(item => item.code)).toEqual([
            "scope-incompatible",
            "unsupported-search-rule"
        ]);
    });


    it("encodes unsafe stylesheet names only in the download filename", () => {
        expect(canonicalSearchStyleFilename("Folder/A:B * style")).toBe("Folder-A-B-style.yaml");
        expect(canonicalSearchStyleFilename("CON")).toBe("_CON.yaml");
        expect(canonicalSearchStyleFilename("道路")).toBe("search-style.yaml");
    });
});
