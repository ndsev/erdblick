import {describe, expect, it} from "vitest";
import {
    combinePreparedSearchAutoStyles,
    defaultSearchStyleFieldOptionsForAnalysis,
    preferredSearchAutoStyleField,
    searchAutoStyleFieldOptions,
    searchAutoStyleFieldOptionsArePortable
} from "../../../app/search/feature-search-auto-style.util";
import type {FeatureSearchStyleRule} from "../../../app/search/search-definition.model";
import type {
    FeatureSearchAutoStyleAnalysis,
    FeatureSearchAutoStyleOption
} from "../../../app/search/feature-search-auto-style.util";

const pedestrianWayScope = {
    attrName: "PEDESTRIAN_WAY",
    attrLayerName: "Routing",
    featureType: "Link",
    mapId: "Classic",
    layerId: "Routing"
};

const readyAttributeAnalysis: FeatureSearchAutoStyleAnalysis = {
    status: "ready",
    concreteScope: "attribute",
    attributeScopes: [pedestrianWayScope],
    matchedFieldNames: [],
    matchedEnumValues: ["PEDESTRIAN_WAY"]
};

const option = (partial: Partial<FeatureSearchAutoStyleOption>): FeatureSearchAutoStyleOption => ({
    label: partial.value ?? "field",
    value: partial.value ?? "field",
    valueKind: partial.valueKind ?? "string",
    enumValues: partial.enumValues ?? [],
    ...partial
});

/** One unmerged warning-sign rule, as contributed by a prepared source owner. */
function automaticRule(
    mapId: string,
    featureType: string,
    field: string
): FeatureSearchStyleRule {
    return {
        autoGenerated: true,
        applicability: {mapId, layerId: "Routing", scope: "attribute"},
        geometry: ["point"],
        filter: [
            {field: "$name", op: "=", value: "WARNING_SIGN"},
            {field: "$feature.typeId", op: "=", value: featureType},
            {field: "$layer", op: "=", value: "Rules"}
        ],
        color: {
            mode: "categories",
            field,
            stops: [{value: "ANIMALS", color: "#112233"}],
            fallbackColor: "#445566"
        }
    };
}

describe("automatic style filter reduction", () => {
    it("needs no extra filter when every source uses the same appearance", () => {
        const sources = [
            [automaticRule("A", "Road", "warningSign")],
            [automaticRule("B", "Lane", "warningSign")]
        ];
        const before = structuredClone(sources);
        const rules = combinePreparedSearchAutoStyles(sources);
        expect(rules).toHaveLength(1);
        expect(rules[0].filter).toEqual([]);
        expect(rules[0].applicability).toBeUndefined();
        expect(sources).toEqual(before);
    });

    it("keeps source separation when equal paths use different palettes", () => {
        const second = automaticRule("B", "Road", "warningSign");
        second.color = {mode: "categories", field: "warningSign",
            stops: [{value: "ANIMALS", color: "#abcdef"}], fallbackColor: "#445566"};
        const rules = combinePreparedSearchAutoStyles([
            [automaticRule("A", "Road", "warningSign")], [second]
        ]);
        expect(rules).toHaveLength(2);
        expect(rules.map(rule => rule.filter)).toEqual([
            [{field: "$feature.mapId", op: "=", value: "A"}],
            [{field: "$feature.mapId", op: "=", value: "B"}]
        ]);
    });

    it("preserves correlated map/type alternatives instead of admitting their Cartesian product", () => {
        const rules = combinePreparedSearchAutoStyles([
            [automaticRule("A", "Road", "warningSign"), automaticRule("A", "Lane", "kind")],
            [automaticRule("B", "Lane", "warningSign"), automaticRule("B", "Road", "kind")]
        ]);
        expect(rules).toHaveLength(2);
        expect(rules[0].filter).toEqual([{
            field: '($feature.mapId == "A") and ($feature.typeId == "Road") or ' +
                '($feature.mapId == "B") and ($feature.typeId == "Lane")',
            op: "=", value: true, customExpression: true
        }]);
    });

    it("does not turn a feature-root rule into an attribute-root rule in mixed-scope searches", () => {
        const feature: FeatureSearchStyleRule = {
            autoGenerated: true,
            applicability: {mapId: "Features", layerId: "Routing", scope: "feature"},
            geometry: ["point"], filter: [], color: {mode: "solid", color: "#112233"}
        };
        const attribute = automaticRule("Attributes", "Road", "warningSign");
        const anotherSource = automaticRule("Other attributes", "Lane", "warningSign");
        const rules = combinePreparedSearchAutoStyles([[feature], [attribute], [anotherSource]]);
        expect(rules).toHaveLength(2);
        expect(rules.map(rule => rule.applicability)).toEqual([{scope: "feature"}, {scope: "attribute"}]);
        expect(rules.every(rule => !rule.filter.length)).toBe(true);
    });
});

describe("feature search auto-style helpers", () => {
    it("prefers the queried enum over numeric siblings sharing the value leaf", () => {
        const analysis: FeatureSearchAutoStyleAnalysis = {
            ...readyAttributeAnalysis,
            matchedFieldNames: ["value", "warningSign"],
            matchedEnumValues: ["SPEED_LIMIT"]
        };
        const numeric = option({
            value: "reference.value",
            valueKind: "integer",
            attrName: pedestrianWayScope.attrName
        });
        const primary = option({
            value: "pedestrianWay",
            valueKind: "enum",
            attrName: pedestrianWayScope.attrName,
            enumValues: ["OTHER"],
            primaryValue: true
        });
        const sign = option({
            value: "properties.*.value",
            valueKind: "enum",
            attrName: pedestrianWayScope.attrName,
            enumValues: ["SPEED_LIMIT", "ANIMALS"]
        });

        expect(searchAutoStyleFieldOptions([numeric, primary, sign], analysis)).toEqual([sign]);
    });

    it("prefers the native speed scalar over shared validity enums and source addresses", () => {
        const analysis: FeatureSearchAutoStyleAnalysis = {
            ...readyAttributeAnalysis,
            attributeScopes: [{...pedestrianWayScope, attrName: "SPEED_LIMIT_METRIC"}],
            matchedEnumValues: ["SPEED_LIMIT_METRIC"]
        };
        const speed = option({value: "attributeValue.speedLimitKmh", valueKind: "integer",
            attrName: "SPEED_LIMIT_METRIC", primaryValue: true});
        const direction = option({value: "validity.*.direction", valueKind: "enum",
            attrName: "SPEED_LIMIT_METRIC", enumValues: ["POSITIVE", "NEGATIVE"]});
        const address = option({value: "_sourceData.*.address", valueKind: "integer",
            attrName: "SPEED_LIMIT_METRIC"});

        expect(preferredSearchAutoStyleField([direction, address, speed], analysis)).toBe(speed);
        // A user explicitly searching direction still gets direction coloring.
        expect(preferredSearchAutoStyleField([direction, address, speed], {
            ...analysis, matchedFieldNames: ["direction"]
        })).toBe(direction);
    });

    it("does not choose an arbitrary scalar when the schema has no primary value", () => {
        const warningSignField = option({
            value: "warningSign",
            attrName: "WARNING_SIGN",
            attrLayerName: "Routing"
        });
        const pedestrianWayFirstField = option({
            value: "pedestrianKind",
            attrName: "PEDESTRIAN_WAY",
            attrLayerName: "Routing"
        });
        const pedestrianWaySecondField = option({
            value: "pedestrianSubtype",
            attrName: "PEDESTRIAN_WAY",
            attrLayerName: "Routing"
        });

        expect(searchAutoStyleFieldOptions(
            [warningSignField, pedestrianWayFirstField, pedestrianWaySecondField],
            readyAttributeAnalysis
        )).toEqual([]);
    });

    it("prefers an attribute-named enum field for WARNING_SIGN", () => {
        const analysis: FeatureSearchAutoStyleAnalysis = {
            status: "ready",
            concreteScope: "attribute",
            attributeScopes: [{
                attrName: "WARNING_SIGN",
                attrLayerName: "Routing",
                featureType: "Link",
                mapId: "Classic",
                layerId: "Routing"
            }],
            matchedFieldNames: [],
            matchedEnumValues: []
        };
        const arbitraryFirstField = option({
            value: "attributeValue.additionalText",
            attrName: "WARNING_SIGN",
            valueKind: "string"
        });
        const warningSignField = option({
            value: "attributeValue.warningSign",
            attrName: "WARNING_SIGN",
            valueKind: "enum",
            enumValues: ["DANGER"]
        });

        expect(preferredSearchAutoStyleField(
            [arbitraryFirstField, warningSignField],
            analysis
        )).toBe(warningSignField);
    });

    it("keeps equally semantic field paths from heterogeneous WARNING_SIGN schemas", () => {
        const analysis: FeatureSearchAutoStyleAnalysis = {
            status: "ready",
            concreteScope: "attribute",
            attributeScopes: [{
                attrName: "WARNING_SIGN",
                attrLayerName: "Routing",
                featureType: "Link",
                mapId: "Classic",
                layerId: "Routing"
            }, {
                attrName: "WARNING_SIGN",
                attrLayerName: "RoadRules",
                featureType: "Road",
                mapId: "Live",
                layerId: "Road"
            }],
            matchedFieldNames: [],
            matchedEnumValues: []
        };
        const classic = option({
            value: "warningSign",
            attrName: "WARNING_SIGN",
            valueKind: "enum",
            mapLayers: [{mapId: "Classic", layerId: "Routing"}]
        });
        const live = option({
            value: "attributeValue.warningSign",
            attrName: "WARNING_SIGN",
            valueKind: "enum",
            mapLayers: [{mapId: "Live", layerId: "Road"}]
        });

        expect(searchAutoStyleFieldOptions([classic, live], analysis))
            .toEqual([classic, live]);
        expect(searchAutoStyleFieldOptionsArePortable([classic, live], analysis)).toBe(false);
    });

    it("allows heterogeneous paths when portable feature-type guards separate them", () => {
        const analysis: FeatureSearchAutoStyleAnalysis = {
            status: "ready",
            concreteScope: "attribute",
            attributeScopes: [{
                attrName: "WARNING_SIGN",
                attrLayerName: "Routing",
                featureType: "Link",
                mapId: "Classic",
                layerId: "Routing"
            }, {
                attrName: "WARNING_SIGN",
                attrLayerName: "RoadRules",
                featureType: "Road",
                mapId: "Live",
                layerId: "Road"
            }],
            matchedFieldNames: [],
            matchedEnumValues: []
        };
        const classic = option({
            value: "warningSign",
            attrName: "WARNING_SIGN",
            featureType: "Link",
            mapLayers: [{mapId: "Classic", layerId: "Routing"}]
        });
        const live = option({
            value: "attributeValue.warningSign",
            attrName: "WARNING_SIGN",
            featureType: "Road",
            mapLayers: [{mapId: "Live", layerId: "Road"}]
        });

        expect(searchAutoStyleFieldOptionsArePortable([classic, live], analysis)).toBe(true);
    });

    it("rejects an automatic field set that leaves a resolved source scope uncovered", () => {
        const analysis: FeatureSearchAutoStyleAnalysis = {
            ...readyAttributeAnalysis,
            attributeScopes: [pedestrianWayScope, {
                ...pedestrianWayScope,
                mapId: "Live",
                layerId: "Road"
            }]
        };
        const classicOnly = option({
            value: "pedestrianKind",
            attrName: "PEDESTRIAN_WAY",
            featureType: "Link",
            mapLayers: [{mapId: "Classic", layerId: "Routing"}]
        });

        expect(searchAutoStyleFieldOptionsArePortable([classicOnly], analysis)).toBe(false);
    });

    it("uses resolved attribute scopes for default style candidates", () => {
        const warningSignField = option({
            value: "warningSign",
            attrName: "WARNING_SIGN"
        });
        const pedestrianWayField = option({
            value: "pedestrianKind",
            attrName: "PEDESTRIAN_WAY"
        });

        expect(defaultSearchStyleFieldOptionsForAnalysis(
            [warningSignField, pedestrianWayField],
            readyAttributeAnalysis
        )).toEqual([pedestrianWayField]);
    });

    it("does not guess automatic style fields for feature-scope searches", () => {
        const roadReasonType = option({
            value: "attributes.layer.RoadRulesLayer.SPEED_LIMIT_METRIC.properties.reason.type",
            featureType: "Road"
        });
        const laneRegulationType = option({
            value: "attributes.layer.LaneRulesLayer.LANE_RIGHT_OF_WAY_REGULATION.attributeValue.laneRightOfWayRegulation.type",
            featureType: "Lane"
        });
        const analysis: FeatureSearchAutoStyleAnalysis = {
            status: "ready",
            concreteScope: "feature",
            attributeScopes: [],
            matchedFieldNames: ["type"],
            matchedEnumValues: []
        };

        expect(searchAutoStyleFieldOptions([laneRegulationType, roadReasonType], analysis)).toEqual([]);
        expect(preferredSearchAutoStyleField([laneRegulationType, roadReasonType], analysis)).toBeUndefined();
    });

    it("does not guess automatic style fields without a resolved attribute scope", () => {
        const enumField = option({
            value: "transitionType",
            attrName: "PROHIBITED_TRANSITION",
            valueKind: "enum",
            enumValues: ["SPEED_LIMIT_END"]
        });
        const analysis: FeatureSearchAutoStyleAnalysis = {
            status: "ready",
            concreteScope: "attribute",
            attributeScopes: [],
            matchedFieldNames: [],
            matchedEnumValues: ["SPEED_LIMIT_END"]
        };

        expect(preferredSearchAutoStyleField([enumField], analysis)).toBeUndefined();
        expect(searchAutoStyleFieldOptions([enumField], analysis)).toEqual([]);
    });

    it("suppresses schema-field auto-styling when query rewriting was suppressed", () => {
        const broadEnumField = option({
            value: "propertyTypeCode",
            attrName: "ATTRIBUTE_PROPERTY",
            valueKind: "enum",
            enumValues: ["WEEKDAY_IN_MONTH"]
        });
        const analysis = {
            ...readyAttributeAnalysis,
            rewriteSuppressed: true
        };

        expect(searchAutoStyleFieldOptions([broadEnumField], analysis)).toEqual([]);
        expect(defaultSearchStyleFieldOptionsForAnalysis([broadEnumField], analysis)).toEqual([]);
    });
});
