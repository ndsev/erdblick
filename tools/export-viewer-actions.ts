/**
 * Catalog flavor of the application: construct Angular controllers and stores,
 * register their public surface, and serialize it. The ordinary async initializer
 * is deliberately not called: it loads config/WASM and starts browser activity.
 */
import "@angular/compiler";
import { APP_BASE_HREF } from "@angular/common";
import { provideHttpClient } from "@angular/common/http";
import { provideZonelessChangeDetection } from "@angular/core";
import { createApplication } from "@angular/platform-browser";
import { provideRouter } from "@angular/router";
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { MessageService } from "primeng/api";
import { registerApplication } from "../app/application-registration";
import { canonicalViewerContractJson, viewerJsonSchema } from "../app/actions/viewer-action.contract";
import { viewerActionClientMessageSchema, viewerActionServerMessageSchema, viewerMcpInfoSchema } from "../app/actions/viewer-action-relay.contract";

const application = await createApplication({
    providers: [
        provideZonelessChangeDetection(),
        provideHttpClient(),
        provideRouter([]),
        { provide: APP_BASE_HREF, useValue: "/" },
        MessageService
    ]
});

try {
    const catalog = registerApplication(application.injector).catalog();
    const canonical = canonicalViewerContractJson(catalog);
    const catalogId = `sha256:${createHash("sha256").update(canonical, "utf8").digest("hex")}`;
    const output = "app/actions/generated";
    mkdirSync(output, { recursive: true });
    writeFileSync(`${output}/web-mcp-actions.json`, `${JSON.stringify({ ...catalog, catalogId }, null, 2)}\n`);
    writeFileSync(`${output}/viewer-actions.canonical.json`, canonical);
    writeFileSync(`${output}/catalog-id.ts`, `// Generated by npm run generate:viewer-actions.\nexport const VIEWER_ACTION_CATALOG_ID = ${JSON.stringify(catalogId)};\n`);
    writeFileSync(`${output}/viewer-action-relay.schema.json`, `${JSON.stringify({
        server: viewerJsonSchema(viewerActionServerMessageSchema),
        client: viewerJsonSchema(viewerActionClientMessageSchema),
        info: viewerJsonSchema(viewerMcpInfoSchema)
    }, null, 2)}\n`);
    console.log(`Viewer action catalog: ${catalogId} (${catalog.actions.length} actions, ${catalog.channels.length} controls)`);
} finally {
    application.destroy();
}
